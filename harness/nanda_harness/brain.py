"""The decision queue: game observations in, model actions out.

The game polls `POST /v1/tick` every couple of seconds and gets back whatever
actions are *ready*. It never waits for a model. Each tick:

  1. the observation is queued as a decision request, one per model-driven
     agent that is due for a refresh;
  2. a worker thread asks Gemini, in the background;
  3. the answer is validated into the fixed vocabulary (schema.py) and parked
     as that agent's current action;
  4. the next tick carries it into the game.

So the model's influence is a standing stance, refreshed every few seconds,
and the round never stalls on a network call. If the model is slow, errors, or
there is no API key at all, the agent simply has no fresh action and the game
falls back to its own scripted policy.
"""

from __future__ import annotations

import json
import os
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from typing import Any, Callable

from . import schema
from .gemini import Gemini, GeminiError
from .limits import Budget
from .metrics import Metrics

PROMPT = """You are {name}, the {role} agent in NANDA Town, a small market simulation
running inside a Roblox world. Other traders are scripted; you are not.

Set your stance for the next few seconds. You will be asked again shortly, so
this is a standing instruction, not a single trade. Answer only with the JSON
object the schema describes: numbers in range and one reason code from the
list. Nothing you write is shown to a player; the game renders its own words
from the reason code.

{role_brief}

The market right now (every number below is generated by the simulation):
{state}

Recent town events:
{ticker}
"""

SELLER_BRIEF = """You sell widgets, and your aim is to end the round with as much money as you
can: that means winning deals, not only pricing high. `quote_pct` is the price
you quote, as a percent of your own list price. `floor_pct` is the lowest
percent of list you will take when a buyer haggles. Buyers open about 20%
under your quote; bargain hunters simply buy the cheapest listing on the
notice board, and loyal buyers stay with their usual seller. The rival sellers
are scripted: they always quote their list price and never move. Deals also
take longer when the town's laws are strict, so a slow round is not
necessarily your price's fault. Act on the evidence below: if buyers are going
elsewhere or walking away, change your stance rather than repeating it."""

BUYER_BRIEF = """You buy widgets, and your aim is to end the round with as many widgets as you
can for as little money as you can. `offer_pct` is your opening offer, as a
percent of the seller's quote. `accept_pct` is the most you will pay, also as
a percent of that quote; if the seller's counter is above it you walk away and
start again with whoever is listed, which costs you most of a minute. The
scripted sellers counter at about 90% of their own list price and go no lower.
Act on the evidence below rather than repeating your stance."""

BRIEF = {"seller": SELLER_BRIEF, "buyer": BUYER_BRIEF}


def _fmt_state(agent: dict, shared: dict) -> str:
    lines = []
    lines.append(f"- you are: {agent.get('name')} ({agent.get('role')})")
    if agent.get("role") == "seller":
        lines.append(f"- your list price: {agent.get('list_cents')} cents per widget")
        lines.append(f"- your current stance: quote {agent.get('quote_pct', 100)}% of list, floor {agent.get('floor_pct', 90)}%")
    else:
        lines.append(f"- your purse: {agent.get('balance_cents')} cents left this round")
        lines.append(f"- your current stance: open at {agent.get('offer_pct', 80)}% of the quote, pay at most {agent.get('accept_pct', 100)}%")
        if agent.get("favourite"):
            lines.append(f"- you usually buy from: {agent['favourite']}")
    for r in agent.get("rivals", []):
        lines.append(
            f"- listing by {r.get('name')}: {r.get('cents')} cents"
            + (f" (reputation {r.get('reputation')})" if r.get("reputation") is not None else "")
            + (" [marked UNVERIFIED by the gate]" if r.get("unverified") else "")
        )
    lines.append(f"- deals you settled this round: {agent.get('deals', 0)}; walked away from: {agent.get('abandoned', 0)}")
    lines.append(f"- your reputation: {agent.get('reputation', 0)}")
    lines.append(f"- deals settled in the whole town this round: {shared.get('deals', 0)}")
    lines.append(f"- town laws: auth {shared.get('auth')}, registry {shared.get('registry')}")
    lines.append(f"- round {shared.get('round')}, {int(shared.get('t', 0))}s in of {int(shared.get('round_seconds', 180))}s")
    return "\n".join(lines)


class Agent:
    def __init__(self, name: str, role: str):
        self.name = name
        self.role = role
        self.seq = 0
        self.action: dict | None = None
        self.requested_at = 0.0
        self.inflight = False
        self.errors = 0
        self.last_error: str | None = None
        self.last_latency_ms: int | None = None


class Brain:
    """Holds the queue, the workers and every agent's current action."""

    def __init__(
        self,
        model_call: Callable[[str, dict], tuple[dict, float, dict]] | None = None,
        model_name: str = "gemini-2.5-flash",
        log_path: str | None = None,
        min_interval: float = 4.0,
        max_workers: int = 2,
        now: Callable[[], float] = time.monotonic,
        budget: Budget | None = None,
        metrics: Metrics | None = None,
        max_agents: int = 8,
        allow_agents: list[str] | None = None,
        echo: bool = True,
    ):
        self.model_call = model_call
        self.model_name = model_name
        self.min_interval = min_interval
        self.now = now
        # the ceiling on model calls, and the counters behind /metrics; a
        # Brain made without them is still a Brain (the tests do that)
        self.budget = budget if budget is not None else Budget()
        self.metrics = metrics if metrics is not None else Metrics()
        self.max_agents = max_agents
        # names a caller may ask for at all. None = any name the game sends,
        # up to max_agents of them.
        self.allow_agents = set(allow_agents) if allow_agents else None
        self.budget_block: str | None = None
        self.fallbacks = 0
        self.agents: dict[str, Agent] = {}
        self.lock = threading.Lock()
        self.pool = ThreadPoolExecutor(max_workers=max_workers, thread_name_prefix="decide")
        self.pending = 0
        self.decisions = 0
        self.errors = 0
        self.ticks = 0
        self.log_path = log_path
        # with a log file, stdout still gets one compact line per decision —
        # no prompt, no answer — so `railway logs` is readable
        self.echo = echo and bool(log_path)
        self._log_lock = threading.Lock()
        if log_path:
            os.makedirs(os.path.dirname(os.path.abspath(log_path)), exist_ok=True)

    # ---------------------------------------------------------------- logging

    def log(self, record: dict) -> None:
        record = {"ts": time.time(), **record}
        line = json.dumps(record, sort_keys=False)
        if self.log_path:
            with self._log_lock:
                with open(self.log_path, "a", encoding="utf-8") as f:
                    f.write(line + "\n")
            if self.echo:
                print(
                    json.dumps(
                        {
                            "ts": round(record["ts"], 3),
                            "ev": "decision",
                            "agent": record.get("agent"),
                            "ok": record.get("ok"),
                            "reason": (record.get("action") or {}).get("reason"),
                            "latency_ms": record.get("latency_ms"),
                            "usd": record.get("usd"),
                            "error": record.get("error"),
                        }
                    ),
                    flush=True,
                )
        else:
            print(line, flush=True)

    # ------------------------------------------------------------------ queue

    @property
    def ready(self) -> bool:
        return self.model_call is not None

    def tick(self, observation: dict) -> list[dict]:
        """One poll from the game: queue what is due, return what is ready.

        Over budget it queues nothing and returns the stances it already has,
        so the game keeps trading on them: a cap must never be felt as an
        error in the town. The Luau side re-stamps a stance it is handed, so a
        held stance stays in force rather than ageing out mid-round.
        """
        self.ticks += 1
        shared = {k: v for k, v in observation.items() if k != "agents"}
        out = []
        agents = observation.get("agents")
        if not isinstance(agents, list):
            agents = []
        for a in agents[: self.max_agents]:
            if not isinstance(a, dict):
                continue
            name, role = a.get("name"), a.get("role")
            if not isinstance(name, str) or role not in schema.RANGES:
                continue
            if len(name) > 64 or (self.allow_agents is not None and name not in self.allow_agents):
                self.metrics.bump("agents_refused")
                continue
            blocked = None
            with self.lock:
                agent = self.agents.get(name)
                if agent is None or agent.role != role:
                    if agent is None and len(self.agents) >= self.max_agents:
                        self.metrics.bump("agents_refused")
                        continue
                    agent = self.agents[name] = Agent(name, role)
                due = (
                    self.ready
                    and not agent.inflight
                    and (self.now() - agent.requested_at) >= self.min_interval
                )
            if due:
                # the only place a model call is ever started, so the only
                # place the budget has to be consulted
                blocked = self.budget.reserve()
                with self.lock:
                    self.budget_block = blocked
                    if blocked:
                        due = False
                    else:
                        agent.inflight = True
                        agent.requested_at = self.now()
                        self.pending += 1
                if blocked:
                    self.metrics.bump("budget_blocked")
                    self.metrics.bump(f"budget_blocked_{blocked}")
            if due:
                self.pool.submit(self._decide, agent, dict(a), dict(shared))
            with self.lock:
                if agent.action:
                    out.append(dict(agent.action))
                else:
                    self.fallbacks += 1
                    self.metrics.bump("fallbacks")
        self.metrics.bump("actions_served", len(out))
        return out

    def _decide(self, agent: Agent, a: dict, shared: dict) -> None:
        prompt = PROMPT.format(
            name=agent.name,
            role=agent.role,
            role_brief=BRIEF[agent.role],
            state=_fmt_state(a, shared),
            ticker="\n".join(f"- {line}" for line in (shared.get("ticker") or [])) or "- (nothing yet)",
        )
        t0 = time.monotonic()
        record: dict[str, Any] = {
            "agent": agent.name,
            "role": agent.role,
            "model": self.model_name,
            "round": shared.get("round"),
            "t": shared.get("t"),
            "prompt": prompt,
        }
        self.metrics.bump("model_calls")
        try:
            raw, seconds, usage = self.model_call(prompt, schema.response_schema(agent.role))  # type: ignore[misc]
            # tokens are spent whether or not the answer turns out to be
            # usable, so the money is booked before the answer is judged
            record["usd"] = round(self.budget.spend(usage or {}), 6)
            self.metrics.model_latency(seconds * 1000)
            record["answer"] = raw  # kept even when it is rejected below
            action = schema.validate(agent.role, raw)
            if action is None:
                raise GeminiError("answer did not fit the vocabulary")
            latency_ms = int(seconds * 1000)
            with self.lock:
                agent.seq += 1
                agent.last_latency_ms = latency_ms
                agent.action = {
                    "agent": agent.name,
                    "role": agent.role,
                    "seq": agent.seq,
                    "source": "llm",
                    "model": self.model_name,
                    "latency_ms": latency_ms,
                    "decided_at": time.time(),
                    **action,
                }
                self.decisions += 1
            record.update(answer=raw, action=action, latency_ms=latency_ms, usage=usage, ok=True)
        except Exception as e:
            self.metrics.bump("model_errors")
            with self.lock:
                agent.errors += 1
                agent.last_error = str(e)
                self.errors += 1
            record.update(ok=False, error=str(e), latency_ms=int((time.monotonic() - t0) * 1000))
        finally:
            # logged before the agent is marked idle, so a caller that waits
            # for the queue to drain can read the record straight afterwards
            self.log(record)
            with self.lock:
                agent.inflight = False
                self.pending = max(0, self.pending - 1)

    # ----------------------------------------------------------------- health

    def llm_state(self) -> str:
        """What the game is told, in one word: ready | no_key | budget.

        `budget` is not an error: the stances already in force are still
        served, and the town keeps trading on them.
        """
        if not self.ready:
            return "no_key"
        return "budget" if self.budget.check() else "ready"

    def health(self) -> dict:
        state = self.llm_state()
        budget = self.budget.snapshot()
        with self.lock:
            return {
                "ok": True,
                "llm": state,
                "model": self.model_name,
                "budget": budget,
                "fallbacks": self.fallbacks,
                "min_interval": self.min_interval,
                "ticks": self.ticks,
                "pending": self.pending,
                "decisions": self.decisions,
                "errors": self.errors,
                "log": self.log_path,
                "agents": {
                    n: {
                        "role": a.role,
                        "seq": a.seq,
                        "errors": a.errors,
                        "last_error": a.last_error,
                        "last_latency_ms": a.last_latency_ms,
                        "action": a.action,
                    }
                    for n, a in self.agents.items()
                },
            }

    def reset(self) -> None:
        with self.lock:
            self.agents.clear()


def gemini_call(model: str, api_key: str, timeout: float = 20.0):
    """A `model_call` backed by the real Gemini API."""
    client = Gemini(api_key=api_key, model=model, timeout=timeout)

    def call(prompt: str, response_schema: dict):
        return client.json_call(prompt, response_schema)

    return call
