"""The HTTP API the Roblox server polls — hardened for the open internet.

  GET  /healthz              liveness, no auth, no secrets: is the process up
  GET  /                     the service banner and the route list, no auth
  GET  /metrics              counts, spend estimate, p50/p90, who is calling
  GET  /v1/health            is there a key, what has it decided, budget state
  POST /v1/tick              one observation from the game -> the actions ready
  GET  /v1/log?n=20          the last n decision records (prompt, answer, latency)
  POST /v1/reset             forget every agent's stance (a fresh round)

Everything but `/healthz` and `/` needs the shared secret, as either

  Authorization: Bearer <token>        (what the Roblox server sends)
  x-nanda-token: <token>               (the older header, still accepted)

and anything else is 401. Above the per-IP or per-server rate limit it is 429
with `Retry-After`; the game's own backoff handles that. Above the *budget* it
is still 200 — see brain.tick: a cap must never be felt as an error in the
town, so the last stance is served and no model is called.

`POST /v1/tick` is the only call in the loop. It returns immediately: it
queues decision requests and hands back whatever the workers have finished.

Request body (generated by the game; no player ever types into it):

  {"round": 2, "t": 41.5, "round_seconds": 180, "deals": 7,
   "auth": "hmac.v1", "registry": "index.v1",
   "ticker": ["buyer-1 settled with seller-a for 3592c", ...],
   "agents": [{"name": "seller-b", "role": "seller", "list_cents": 2095,
               "quote_pct": 100, "floor_pct": 90, "deals": 2, "abandoned": 1,
               "reputation": 1, "rivals": [{"name": "seller-a", "cents": 1995}]}]}

Response:

  {"actions": [{"agent": "seller-b", "kind": "seller_pricing", "seq": 3,
                "quote_pct": 92, "floor_pct": 86, "reason": "undercut_rival",
                "source": "llm", "model": "gemini-2.5-flash",
                "latency_ms": 1180, "age_ms": 620}],
   "llm": "ready", "pending": 1, "served_ms": 0}
"""

from __future__ import annotations

import hmac
import json
import re
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

from .limits import RateLimiter
from .metrics import Metrics

MAX_BODY = 256 * 1024
SAFE_ID = re.compile(r"[^A-Za-z0-9._:-]")
VERSION = "1.1.0"

PUBLIC = ("/healthz", "/", "/v1")


def _safe_id(v: str | None, limit: int = 64) -> str | None:
    """A caller-supplied identifier, reduced to something loggable."""
    if not isinstance(v, str) or not v:
        return None
    return SAFE_ID.sub("", v)[:limit] or None


class Handler(BaseHTTPRequestHandler):
    server_version = f"nanda-harness/{VERSION}"
    protocol_version = "HTTP/1.1"
    brain = None  # set by serve()
    token = None
    metrics: Metrics = None  # type: ignore[assignment]
    ip_limit: RateLimiter = None  # type: ignore[assignment]
    server_limit: RateLimiter = None  # type: ignore[assignment]
    global_limit: RateLimiter = None  # type: ignore[assignment]
    auth_limit: RateLimiter = None  # type: ignore[assignment]
    trust_proxy = True
    quiet = True
    log_health = False

    # ------------------------------------------------------------- plumbing

    def log_message(self, fmt, *args):  # the access log below replaces it
        pass

    def access(self, status: int, extra: dict | None = None) -> None:
        if not self.log_health and self.path.startswith("/healthz") and status == 200:
            return
        rec = {
            "ts": round(time.time(), 3),
            "ev": "http",
            "method": self.command,
            "path": urlparse(self.path).path[:120],
            "status": status,
            "ms": int((time.monotonic() - self._t0) * 1000),
            "ip": self.client_ip,
            "server": self.server_id,
        }
        if extra:
            rec.update(extra)
        # no header, body, prompt, API key or bearer token is ever in here
        print(json.dumps(rec), flush=True)

    def _send(self, code: int, obj, headers: dict | None = None) -> None:
        body = json.dumps(obj).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        for k, v in (headers or {}).items():
            self.send_header(k, str(v))
        self.end_headers()
        self.wfile.write(body)
        self.status = code

    # ------------------------------------------------------------- identity

    @property
    def client_ip(self) -> str:
        if getattr(self, "_ip", None):
            return self._ip  # type: ignore[return-value]
        ip = self.client_address[0] if self.client_address else "?"
        if self.trust_proxy:
            fwd = self.headers.get("x-forwarded-for")
            if fwd:
                ip = _safe_id(fwd.split(",")[0].strip(), 64) or ip
        self._ip = ip
        return ip

    @property
    def server_id(self) -> str | None:
        """The Roblox server instance (game.JobId), if it said who it is."""
        if getattr(self, "_server", "unset") != "unset":
            return self._server  # type: ignore[return-value]
        self._server = _safe_id(self.headers.get("x-nanda-server"))
        return self._server

    def _authorized(self) -> bool:
        if not self.token:
            return True
        offered = ""
        auth = self.headers.get("authorization") or ""
        if auth[:7].lower() == "bearer ":
            offered = auth[7:].strip()
        if not offered:
            offered = (self.headers.get("x-nanda-token") or "").strip()
        return bool(offered) and hmac.compare_digest(offered, self.token)

    def _read_json(self):
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            return None
        if n <= 0 or n > MAX_BODY:
            return None
        try:
            return json.loads(self.rfile.read(n).decode("utf-8"))
        except Exception:
            return None

    def _drain(self) -> None:
        """Read and discard a body, so the connection can be reused."""
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            n = 0
        if 0 < n <= MAX_BODY:
            try:
                self.rfile.read(n)
            except Exception:
                pass

    # -------------------------------------------------------------- the gate

    def _gate(self, path: str) -> bool:
        """Rate limit, then authenticate. True if the request may proceed."""
        ok, retry = self.global_limit.allow("*")
        if not ok:
            self._drain()
            self.metrics.bump("rate_limited_global")
            self._send(429, {"error": "too many requests"}, {"Retry-After": retry})
            return False
        ok, retry = self.ip_limit.allow(self.client_ip)
        if not ok:
            self._drain()
            self.metrics.bump("rate_limited_ip")
            self._send(429, {"error": "too many requests from this address"}, {"Retry-After": retry})
            return False
        if path in PUBLIC:
            return True
        # the failed-authentication window counts failures only, so a caller
        # with the right token is never throttled by someone else's guessing
        over, retry = self.auth_limit.peek(self.client_ip)
        if over:
            self._drain()
            self.metrics.bump("rate_limited_auth")
            self._send(429, {"error": "too many failed attempts from this address"}, {"Retry-After": retry})
            return False
        if not self._authorized():
            self._drain()
            self.metrics.bump("unauthorized")
            self.auth_limit.allow(self.client_ip)
            self._send(401, {"error": "unauthorized"})
            return False
        sid = self.server_id
        if sid and path == "/v1/tick":
            ok, retry = self.server_limit.allow(sid)
            if not ok:
                self._drain()
                self.metrics.bump("rate_limited_server")
                self._send(429, {"error": "too many requests from this game server"}, {"Retry-After": retry})
                return False
        return True

    # -------------------------------------------------------------- routing

    def handle_one_request(self):  # time and count every request, whatever it is
        self._t0 = time.monotonic()
        self.status = 0
        self._ip = None
        self._server = "unset"
        super().handle_one_request()
        if self.status:
            self.metrics.request(
                self.status,
                getattr(self, "_ip", None),
                self._server if self._server != "unset" else None,
                rejected=self.status >= 400,
            )
            self.access(self.status)

    def do_GET(self):
        route = urlparse(self.path)
        path = route.path.rstrip("/") or "/"
        if not self._gate(path):
            return
        if path == "/healthz":
            h = self.brain.health()
            return self._send(
                200,
                {
                    "ok": True,
                    "service": "nanda-harness",
                    "version": VERSION,
                    "llm": h["llm"],
                    "model": h["model"],
                    "uptime_s": round(time.time() - self.metrics.started, 1),
                },
            )
        if path in ("/", "/v1"):
            return self._send(
                200,
                {
                    "service": "nanda-harness",
                    "version": VERSION,
                    "auth": "Authorization: Bearer <token>",
                    "routes": ["/healthz", "/metrics", "/v1/health", "/v1/tick", "/v1/log", "/v1/reset"],
                },
            )
        if path == "/metrics":
            m = self.metrics.snapshot()
            h = self.brain.health()
            m["llm"] = h["llm"]
            m["model"] = h["model"]
            m["budget"] = h["budget"]
            m["decisions"] = h["decisions"]
            m["model_errors"] = h["errors"]
            m["fallbacks"] = h["fallbacks"]
            m["ticks"] = h["ticks"]
            m["limits"] = {
                "ip": self.ip_limit.snapshot(),
                "roblox_server": self.server_limit.snapshot(),
                "global": self.global_limit.snapshot(),
            }
            return self._send(200, m)
        if path == "/v1/health":
            return self._send(200, self.brain.health())
        if path == "/v1/log":
            q = parse_qs(route.query)
            try:
                n = int((q.get("n") or ["20"])[0])
            except ValueError:
                n = 20
            return self._send(200, {"records": tail_log(self.brain.log_path, n)})
        return self._send(404, {"error": "no such route"})

    def do_POST(self):
        route = urlparse(self.path)
        path = route.path.rstrip("/") or "/"
        if not self._gate(path):
            return
        if path == "/v1/reset":
            self._drain()
            self.brain.reset()
            return self._send(200, {"ok": True})
        if path != "/v1/tick":
            self._drain()
            return self._send(404, {"error": "no such route"})
        t0 = time.monotonic()
        obs = self._read_json()
        if not isinstance(obs, dict):
            return self._send(400, {"error": "expected a JSON object"})
        actions = self.brain.tick(obs)
        now = time.time()
        for a in actions:
            a["age_ms"] = int(max(0.0, now - a.get("decided_at", now)) * 1000)
            a.pop("decided_at", None)
        h = self.brain.health()
        served = (time.monotonic() - t0) * 1000
        self.metrics.serve_latency(served)
        return self._send(
            200,
            {
                "actions": actions,
                "llm": h["llm"],
                "model": h["model"],
                "pending": h["pending"],
                "errors": h["errors"],
                "budget": h["budget"]["state"],
                "served_ms": int(served),
            },
        )


def tail_log(path: str | None, n: int) -> list:
    if not path:
        return []
    try:
        with open(path, "r", encoding="utf-8") as f:
            lines = f.readlines()[-max(0, min(n, 500)) :]
    except OSError:
        return []
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except ValueError:
            pass
    return out


def serve(
    brain,
    host: str = "127.0.0.1",
    port: int = 8790,
    token: str | None = None,
    quiet: bool = True,
    metrics: Metrics | None = None,
    per_ip_per_minute: int = 120,
    per_server_per_minute: int = 45,
    global_per_minute: int = 600,
    auth_failures_per_minute: int = 20,
    trust_proxy: bool = True,
    log_health: bool = False,
):
    """A ThreadingHTTPServer with the gate, the limits and the counters on it."""
    metrics = metrics if metrics is not None else getattr(brain, "metrics", None) or Metrics()
    handler = type(
        "BoundHandler",
        (Handler,),
        {
            "brain": brain,
            "token": token,
            "quiet": quiet,
            "metrics": metrics,
            "ip_limit": RateLimiter(per_ip_per_minute, 60.0),
            "server_limit": RateLimiter(per_server_per_minute, 60.0),
            "global_limit": RateLimiter(global_per_minute, 60.0),
            "auth_limit": RateLimiter(auth_failures_per_minute, 60.0),
            "trust_proxy": trust_proxy,
            "log_health": log_health,
        },
    )
    httpd = ThreadingHTTPServer((host, port), handler)
    httpd.daemon_threads = True
    return httpd
