"""The HTTP API the Roblox server polls.

  GET  /v1/health            is the harness up, is there a key, what has it decided
  POST /v1/tick              one observation from the game -> the actions that are ready
  GET  /v1/log?n=20          the last n decision records (prompt, answer, latency)
  POST /v1/reset             forget every agent's stance (a fresh round)

`POST /v1/tick` is the only call in the loop. It returns immediately: it queues
decision requests and hands back whatever the workers have finished. See
brain.py.

Request body (generated by the game; no player ever types into it):

  {"round": 2, "t": 41.5, "round_seconds": 180, "deals": 7,
   "auth": "hmac.v1", "registry": "index.v1",
   "ticker": ["buyer-1 settled with seller-a for 3592c", ...],
   "agents": [{"name": "seller-b", "role": "seller", "list_cents": 2095,
               "quote_pct": 100, "floor_pct": 90, "deals": 2, "abandoned": 1,
               "reputation": 1, "rivals": [{"name": "seller-a", "cents": 1995}]}]}

Response:

  {"actions": [{"agent": "seller-b", "kind": "seller_pricing", "seq": 3,
                "quote_pct": 92, "floor_pct": 86, "reason": "undercut_rival",
                "source": "llm", "model": "gemini-2.5-flash",
                "latency_ms": 1180, "age_ms": 620}],
   "llm": "ready", "pending": 1, "served_ms": 0}
"""

from __future__ import annotations

import json
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

MAX_BODY = 256 * 1024


class Handler(BaseHTTPRequestHandler):
    server_version = "nanda-harness/1.0"
    brain = None  # set by serve()
    token = None
    quiet = True

    # ------------------------------------------------------------- plumbing

    def log_message(self, fmt, *args):  # the brain writes the JSON lines
        if not self.quiet:
            super().log_message(fmt, *args)

    def _send(self, code: int, obj) -> None:
        body = json.dumps(obj).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _authorized(self) -> bool:
        if not self.token:
            return True
        return self.headers.get("x-nanda-token") == self.token

    def _read_json(self):
        try:
            n = int(self.headers.get("Content-Length") or 0)
        except ValueError:
            return None
        if n <= 0 or n > MAX_BODY:
            return None
        try:
            return json.loads(self.rfile.read(n).decode("utf-8"))
        except Exception:
            return None

    # -------------------------------------------------------------- routing

    def do_GET(self):
        route = urlparse(self.path)
        if route.path in ("/", "/v1"):
            return self._send(200, {"service": "nanda-harness", "routes": ["/v1/health", "/v1/tick", "/v1/log", "/v1/reset"]})
        if not self._authorized():
            return self._send(401, {"error": "bad token"})
        if route.path == "/v1/health":
            return self._send(200, self.brain.health())
        if route.path == "/v1/log":
            q = parse_qs(route.query)
            n = int((q.get("n") or ["20"])[0])
            return self._send(200, {"records": tail_log(self.brain.log_path, n)})
        return self._send(404, {"error": "no such route"})

    def do_POST(self):
        route = urlparse(self.path)
        if not self._authorized():
            return self._send(401, {"error": "bad token"})
        if route.path == "/v1/reset":
            self.brain.reset()
            return self._send(200, {"ok": True})
        if route.path != "/v1/tick":
            return self._send(404, {"error": "no such route"})
        t0 = time.monotonic()
        obs = self._read_json()
        if not isinstance(obs, dict):
            return self._send(400, {"error": "expected a JSON object"})
        actions = self.brain.tick(obs)
        now = time.time()
        for a in actions:
            a["age_ms"] = int(max(0.0, now - a.get("decided_at", now)) * 1000)
            a.pop("decided_at", None)
        h = self.brain.health()
        return self._send(
            200,
            {
                "actions": actions,
                "llm": h["llm"],
                "model": h["model"],
                "pending": h["pending"],
                "errors": h["errors"],
                "served_ms": int((time.monotonic() - t0) * 1000),
            },
        )


def tail_log(path: str | None, n: int) -> list:
    if not path:
        return []
    try:
        with open(path, "r", encoding="utf-8") as f:
            lines = f.readlines()[-max(0, min(n, 500)) :]
    except OSError:
        return []
    out = []
    for line in lines:
        try:
            out.append(json.loads(line))
        except ValueError:
            pass
    return out


def serve(brain, host: str = "127.0.0.1", port: int = 8790, token: str | None = None, quiet: bool = True):
    handler = type("BoundHandler", (Handler,), {"brain": brain, "token": token, "quiet": quiet})
    httpd = ThreadingHTTPServer((host, port), handler)
    httpd.daemon_threads = True
    return httpd
