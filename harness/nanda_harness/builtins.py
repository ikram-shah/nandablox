"""The two slot occupants the gateway serves itself.

  rules          the four-line rule monitor from docs/market-design.md
  gemini-seller  the hosted Gemini seller, speaking the `decide` shape

Each is a function from a `decide` request to a `decide` answer — exactly
what an outside endpoint receives and returns — so the gateway calls them the
way it calls anyone, minus the network, and `POST /v1/builtin/<name>/decide`
serves them over HTTP for anyone who wants to see the shape.
"""

from __future__ import annotations

from .brain import Agent, Brain

# ------------------------------------------------------------------ rules


def rule_verdict(case: dict, signatures: bool, market: dict | None = None) -> tuple[str, str]:
    """The built-in rule monitor, in full (docs/market-design.md):

        if listing.twin and signatures are off:    escalate  -- can't tell which is real
        if price >= 0.85 * market or ratings >= 5: allow     -- ordinary business
        if price <  0.50 * market and age < 60 s:  block     -- almost always a scam
        otherwise:                                  escalate  -- the gray zone

    A case with no usable market price can only be judged on its ratings.
    """
    if case.get("twin") and not signatures:
        return "escalate", "twin stall, signatures off: can't tell which is real"
    price = _num(case.get("price"))
    mkt = _num(case.get("market"))
    if mkt is None and market:
        mkt = _num(market.get(case.get("good")))
    ratings = _num(case.get("ratings")) or 0
    age = _num(case.get("age_s"))
    if ratings >= 5:
        return "allow", "ordinary business"
    if price is None or not mkt:
        return "escalate", "no market price to compare with"
    if price >= 0.85 * mkt:
        return "allow", "ordinary business"
    if price < 0.50 * mkt and age is not None and age < 60:
        return "block", f"{round(100 * (1 - price / mkt))}% below market and new"
    return "escalate", f"{round(100 * (1 - price / mkt))}% below market: the gray zone"


def _num(v):
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return None
    return v


def rules_decide(req: dict) -> dict:
    lever = req.get("lever") if isinstance(req.get("lever"), dict) else {}
    signatures = lever.get("signatures", True) is not False
    market = req.get("market") if isinstance(req.get("market"), dict) else None
    out = []
    for c in req.get("cases") or []:
        if isinstance(c, dict) and isinstance(c.get("id"), str):
            verdict, reason = rule_verdict(c, signatures, market)
            out.append({"case": c["id"], "verdict": verdict, "reason": reason})
    return {"verdicts": out}


# ----------------------------------------------------------- gemini-seller

MARKET_PROMPT = """You are {name}, a seller in NANDA Market, a market square simulated inside a
Roblox world. Other traders are mostly scripted; you are driven by a model.

Set your price for the next few seconds. You will be asked again shortly, so
this is a standing instruction, not a single trade. Answer only with the JSON
object the schema describes: numbers in range and one reason code from the
list. Nothing you write is shown to a player.

`quote_pct` is the price you ask, as a percent of the market price of your
good (the median of what it actually sold for in the last minute). Buyers are
agents that mostly pick the cheapest stall, so pricing low wins customers and
pricing high earns more per sale. If you sell out, you could ask more; if
nobody buys, you are probably too dear. `floor_pct` is ignored in this market;
set it equal to quote_pct.

Your stall right now (every number is generated by the simulation; prices in
integer cents):
{state}
"""


class MarketBrain(Brain):
    """The hosted Gemini seller, re-pointed at the market's numbers.

    Everything that keeps it cheap is inherited unchanged: the background
    queue (a decide call never waits on a model), one call per trader per
    `min_interval`, the budget caps, `max_agents`, the fixed vocabulary.
    """

    def prompt(self, agent: Agent, a: dict, shared: dict) -> str:
        lines = [
            f"- good: {a.get('good')}",
            f"- your price: {a.get('price')} cents; the market price: {a.get('market')} cents",
            f"- stock left: {a.get('stock')}",
            f"- units you sold in the last minute: {a.get('sold_last_min')}",
            f"- signature checks: {'on' if (shared.get('lever') or {}).get('signatures', True) else 'off'}",
            f"- market prices now: {shared.get('market')}",
        ]
        return MARKET_PROMPT.format(name=agent.name, state="\n".join(lines))


class GeminiSeller:
    """`decide` for the agent slot, backed by a MarketBrain.

    A decision is handed to the brain as a seller observation; the stance the
    brain has (if any) comes back as `quote_pct`, which is turned into a
    `set_price` against the market price *in this request*, so a stance set
    a few seconds ago follows the market rather than freezing a stale price.
    No stance yet (first sight, model slow, no key, over budget with nothing
    held): no action, and the game's built-in seller carries on.
    """

    def __init__(self, brain: MarketBrain, idle_s: float = 60.0, now=None):
        self.brain = brain
        self.idle_s = idle_s
        self.now = now or brain.now
        self.seen: dict[str, float] = {}

    def _evict_idle(self) -> None:
        """A trader not asked about for `idle_s` gives its slot back, so the
        `max_agents` seats follow the market that is running now rather than
        the first traders the gateway ever saw."""
        t = self.now()
        with self.brain.lock:
            for name in [n for n, at in self.seen.items() if t - at >= self.idle_s]:
                a = self.brain.agents.get(name)
                if a is None or not a.inflight:
                    self.brain.agents.pop(name, None)
                    self.seen.pop(name, None)

    def decide(self, req: dict) -> dict:
        self._evict_idle()
        shared = {k: req.get(k) for k in ("t", "market", "lever", "server")}
        decisions = [d for d in (req.get("decisions") or []) if isinstance(d, dict) and d.get("role") == "seller"]
        by_name = {}
        agents = []
        for d in decisions:
            name = d.get("agent")
            mkt = _num(d.get("market"))
            if not isinstance(name, str) or not mkt or mkt <= 0:
                continue
            by_name[name] = d
            agents.append({**d, "name": name, "role": "seller"})
        stances = self.brain.tick({**shared, "agents": agents})
        t = self.now()
        with self.brain.lock:
            for name in by_name:
                if name in self.brain.agents:
                    self.seen[name] = t
        actions = []
        for s in stances:
            d = by_name.get(s.get("agent"))
            if d is None:
                continue
            actions.append(
                {
                    "agent": d["agent"],
                    "set_price": max(1, int(round(d["market"] * s["quote_pct"] / 100.0))),
                    "reason": s.get("reason"),
                }
            )
        return {"actions": actions}

    def health(self) -> dict:
        h = self.brain.health()
        return {k: h[k] for k in ("llm", "model", "budget", "decisions", "errors", "pending", "fallbacks")}
